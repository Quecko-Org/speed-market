interface Config {
  count: number;
  minSize: number;
  maxSize: number;
  spread: number;
  launchPower: number;
  gravity: number;
  fadeSpeed: number;
  spinSpeed: number;
}

const CONFIG: Config = {
  count: 70,
  minSize: 14,
  maxSize: 36,
  spread: 7,
  launchPower: 13,
  gravity: 0.3,
  fadeSpeed: 0.012,
  spinSpeed: 14,
};

export interface ConfettiHandle {
  launch: (originEl: HTMLElement) => void;
}

interface Piece {
  x: number;
  y: number;
  vx: number;
  vy: number;
  rot: number;
  rotV: number;
  alpha: number;
  idx: number;
  def: ShapeDef;
  scale: number;
}

const ConfettiCanvas = forwardRef<ConfettiHandle>((_, ref) => {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const rafRef = useRef<number | null>(null);
  const pathCacheRef = useRef<Path2D[] | null>(null);

  useImperativeHandle(ref, () => ({
    launch(originEl: HTMLElement) {
      const canvas = canvasRef.current;
      if (!canvas) return;

      const ctx = canvas.getContext("2d");
      if (!ctx) return;

      if (!pathCacheRef.current) {
        pathCacheRef.current = SHAPE_DEFS.map((s) => new Path2D(s.d));
      }
      const PATH_CACHE = pathCacheRef.current;

      canvas.width = window.innerWidth;
      canvas.height = window.innerHeight;

      const rect = originEl.getBoundingClientRect();
      const ox = rect.left + rect.width / 2;
      const oy = rect.top;

      const pieces: Piece[] = Array.from({ length: CONFIG.count }, () => {
        const idx = Math.floor(Math.random() * SHAPE_DEFS.length);
        const def = SHAPE_DEFS[idx];
        const targetSize =
          Math.random() * (CONFIG.maxSize - CONFIG.minSize) + CONFIG.minSize;
        return {
          x: ox,
          y: oy,
          vx: (Math.random() - 0.5) * CONFIG.spread,
          vy: -(Math.random() * CONFIG.launchPower + 3),
          rot: Math.random() * 360,
          rotV: (Math.random() - 0.5) * CONFIG.spinSpeed,
          alpha: 1,
          idx,
          def,
          scale: targetSize / Math.max(def.vw, def.vh),
        };
      });

      if (rafRef.current !== null) cancelAnimationFrame(rafRef.current);

      function draw() {
        if (!ctx) return;
        ctx.clearRect(0, 0, canvas!.width, canvas!.height);
        let alive = false;

        for (const p of pieces) {
          p.x += p.vx;
          p.vy += CONFIG.gravity;
          p.y += p.vy;
          p.rot += p.rotV;
          p.alpha -= CONFIG.fadeSpeed;
          if (p.alpha <= 0) continue;
          alive = true;

          ctx.save();
          ctx.globalAlpha = p.alpha;
          ctx.translate(p.x, p.y);
          ctx.rotate((p.rot * Math.PI) / 180);
          ctx.translate((-p.def.vw / 2) * p.scale, (-p.def.vh / 2) * p.scale);
          ctx.scale(p.scale, p.scale);

          const path = PATH_CACHE[p.idx];
          if (p.def.type === "stroke") {
            ctx.strokeStyle = p.def.color;
            ctx.lineWidth = p.def.sw ?? 1;
            ctx.lineCap = "round";
            ctx.lineJoin = "round";
            ctx.stroke(path);
          } else {
            ctx.fillStyle = p.def.color;
            ctx.fill(path);
          }
          ctx.restore();
        }

        if (alive) {
          rafRef.current = requestAnimationFrame(draw);
        } else {
          ctx.clearRect(0, 0, canvas!.width, canvas!.height);
        }
      }

      draw();
    },
  }));

  useEffect(() => {
    return () => {
      if (rafRef.current !== null) cancelAnimationFrame(rafRef.current);
    };
  }, []);

  return (
    <canvas
      ref={canvasRef}
      style={{
        position: "fixed",
        top: 0,
        left: 0,
        width: "100%",
        height: "100%",
        pointerEvents: "none",
        zIndex: 9999,
      }}
    />
  );
});

ConfettiCanvas.displayName = "ConfettiCanvas";
export default ConfettiCanvas;
